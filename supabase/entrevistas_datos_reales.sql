-- 1) Tabla de entrevistas ------------------------------------------------------
create table if not exists public.entrevistas (
  id            bigint generated by default as identity primary key,
  comercio_id   bigint not null unique references public.comercios(id) on delete cascade,
  giro          text   not null,
  tipo_negocio  text,
  entrevistado  text   not null,
  fecha         date,                                   -- en el documento aparece "Por completar"
  estado        text   not null default 'realizada' check (estado in ('realizada', 'pendiente')),
  respuestas    jsonb  not null default '[]'::jsonb,    -- [{ "pregunta": "...", "respuesta": "..." | null }]
  observaciones text[] not null default '{}',           -- observaciones del equipo (locales sin entrevista)
  necesidades   text[] not null default '{}',           -- etiquetas: pedidos, catalogo, ubicacion, horarios, ...
  sintesis      text,
  created_at    timestamptz not null default now()
);
alter table public.entrevistas enable row level security;
drop policy if exists "admin lee entrevistas" on public.entrevistas;
drop policy if exists "dueño lee su entrevista" on public.entrevistas;
create policy "admin lee entrevistas" on public.entrevistas for select to authenticated
  using (exists (select 1 from public.perfiles p where p.id = auth.uid() and p.rol = 'admin' and p.estado = 'activo'));
create policy "dueño lee su entrevista" on public.entrevistas for select to authenticated
  using (exists (select 1 from public.comercios c where c.id = comercio_id and c.propietario_id = auth.uid()));
revoke all on public.entrevistas from anon;
grant select on public.entrevistas to authenticated;

